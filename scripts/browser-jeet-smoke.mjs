import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const output = path.join(root, 'artifacts/jeet-browser');
fs.mkdirSync(output, { recursive: true });
(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  try{
    const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
    const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.error('BROWSER ERROR:',e.stack)});
    await page.goto('file://' + path.join(root, 'android/app/src/main/assets/www/index.html'));await page.getByRole('heading',{name:/نسخة أقوى منك/}).waitFor();
    await page.screenshot({path:path.join(output, 'home.png'),fullPage:true});
    console.log('Home rendered.');
    await page.getByRole('button',{name:'خطتي',exact:true}).click();
    await page.getByRole('button',{name:'إضافة جدول',exact:true}).click();
    await page.getByLabel('اسم الجدول',{exact:true}).fill('قوتي الجديدة');
    await page.getByRole('button',{name:'إضافة تمرين',exact:true}).click();
    await page.getByRole('button',{name:'إنشاء تمرين جديد'}).click();
    await page.getByLabel('اسم التمرين',{exact:true}).fill('ضغط مخصص');
    await page.getByLabel('المجموعات',{exact:true}).fill('2');
    await page.getByLabel('التكرارات',{exact:true}).fill('8–12');
    await page.getByRole('button',{name:'حفظ التمرين',exact:true}).click();
    await page.getByRole('button',{name:'حفظ الجدول',exact:true}).click();
    let state=await page.evaluate(()=>JSON.parse(localStorage.getItem('jeet.v1')));
    const custom=state.plans.find(p=>p.name==='قوتي الجديدة');assert.equal(custom.exercises[0].name,'ضغط مخصص');assert.equal(custom.exercises[0].sets,2);
    await page.screenshot({path:path.join(output, 'plans.png'),fullPage:true});
    console.log('Custom exercise and plan saved.');
    await page.getByRole('button',{name:'التمرين',exact:true}).click();
    await page.getByLabel('جدول الحصة').selectOption(custom.id);
    const optional=page.getByRole('button',{name:'أريد التدريب اليوم'});if(await optional.isVisible())await optional.click();
    await page.getByRole('button',{name:'ابدأ الحصة',exact:true}).click();
    await page.getByLabel('وزن المجموعة 1',{exact:true}).fill('20');
    await page.getByLabel('تكرارات المجموعة 1',{exact:true}).fill('10');
    await page.getByRole('button',{name:'تأكيد المجموعة 1',exact:true}).click();
    await page.getByRole('timer').waitFor();
    await page.screenshot({path:path.join(output, 'workout.png'),fullPage:true});
    await page.getByRole('button',{name:'+٣٠ ثانية',exact:true}).click();
    assert.match(await page.getByRole('timer').innerText(),/1:5|2:0/);
    await page.getByRole('button',{name:'إنهاء وحفظ الحصة',exact:true}).click();
    await page.getByRole('button',{name:'حفظ الحصة',exact:true}).click();
    state=await page.evaluate(()=>JSON.parse(localStorage.getItem('jeet.v1')));assert.equal(state.sessions.length,1);assert.equal(state.sessions[0].exercises[0].sets.length,1);assert.equal(state.draft,null);
    assert.equal(await page.getByRole('timer').count(),0);console.log('Set completion, automatic rest, extension and partial-session save verified.');
    await page.getByRole('button',{name:'المزيد',exact:true}).click();await page.getByRole('button',{name:'الوزن والقياسات'}).click();
    await page.getByLabel('الخصر · سم',{exact:true}).fill('90');await page.getByLabel('الوزن · كغ',{exact:true}).fill('75');await page.getByRole('button',{name:'حفظ القياس',exact:true}).click();
    await page.getByRole('button',{name:'تقدمي',exact:true}).click();await page.screenshot({path:path.join(output, 'progress.png'),fullPage:true});
    await page.getByRole('button',{name:'المزيد',exact:true}).click();
    const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'تصدير نسخة احتياطية'}).click();const download=await downloadPromise;await download.saveAs(path.join(output, 'backup.json'));
    const backup=JSON.parse(fs.readFileSync(path.join(output, 'backup.json'),'utf8'));assert.equal(backup.app,'jeet');assert.equal(backup.data.sessions.length,1);assert.equal(backup.data.measures.length,1);
    await page.locator('input[type=file][accept="application/json,.json"]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"unrelated":true}')});
    assert.match(await page.locator('[role=alert]').last().innerText(),/نسخة جيت/);assert.equal(await page.getByRole('dialog').count(),0);
    await page.locator('input[type=file][accept="application/json,.json"]').setInputFiles(path.join(output, 'backup.json'));await page.getByRole('dialog').waitFor();await page.getByRole('button',{name:'استبدال البيانات بهذه النسخة'}).click();console.log('Measurements, backup download, invalid import rejection and valid restore verified.');
    await page.reload();await page.getByRole('button',{name:'خطتي',exact:true}).click();await page.getByRole('heading',{name:'قوتي الجديدة',exact:true}).waitFor();
    for(const width of [320,390,768]){await page.setViewportSize({width,height:844});const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);assert.equal(overflow,false,'Overflow at '+width);await page.screenshot({path:path.join(output, 'plans-'+width+'.png'),fullPage:true});}
    assert.deepEqual(errors,[]);console.log('Persistence and responsive widths 320/390/768 passed. No browser exceptions.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
